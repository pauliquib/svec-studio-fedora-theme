def render_icon(attrs: str, inner: str, variant: str) -> str:
    if variant == "SvecStudio-Accent":
        # Vzor Breeze: class="ColorScheme-*" a stroke="currentColor" musí být
        # na STEJNÉM elementu — QtSvg resolvuje currentColor na elementu,
        # kde je stroke atribut (na rootu svg by vyšla černá).
        m = _VIEWBOX_RE.search(attrs)
        viewbox = m.group(1) if m else "0 0 24 24"
        paint = _NONPAINT_RE.sub("", attrs).strip() or 'fill="none" stroke="currentColor"'
        return (
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}">\n'
            f"  {CCS_STYLE}\n"
            f'  <g class="ColorScheme-Accent" {paint}>\n{inner}\n  </g>\n'
            f"</svg>\n"
        )
    color = WHITE if variant == "SvecStudio-White" else BLACK
    return (
        f"<svg{attrs.replace('currentColor', color)}>\n"
        f"{inner.replace('currentColor', color)}\n"
        f"</svg>\n"
    )


