def index_theme(theme: str, meta: dict[str, str]) -> str:
    dirs = list(dict.fromkeys(["apps", *FDO_MAP]))
    sections = [
        "[Icon Theme]",
        f"Name=Svec Studio Icons ({meta['label']})",
        f"Comment={meta['comment']} — v{meta['version']}",
        "Inherits=breeze",
        "DisplayDepth=32",
    ]
    if meta.get("follows_color_scheme"):
        sections.append("FollowsColorScheme=true")
    sections += [
        "Directories=" + ",".join(f"scalable/{d}" for d in dirs),
        "",
    ]
    for d in dirs:
        sections += [
            f"[scalable/{d}]",
            f"Context={_CONTEXT_NAMES.get(d, 'Applications')}",
            "Size=48",
            "MinSize=16",
            "MaxSize=256",
            "Type=Scalable",
            "",
        ]
    return "\n".join(sections)


def collect_icons() -> dict[str, tuple[str, str]]:
    """icon name → (svg attrs, inner); zdroj = src/<name>.svg."""
    icons: dict[str, tuple[str, str]] = {}
    for f in sorted(SRC_DIR.glob("*.svg")):
        icons[f.stem] = split_svg(f.read_text(encoding="utf-8"))
    return icons


def build_themes(out_dir: Path) -> None:
    icons = collect_icons()
    logo = LOGO_SVG.read_text(encoding="utf-8")
    missing = {src for m in FDO_MAP.values() for src in m.values() if src not in icons and src != "cz.svec.Studio"}
    if missing:
        print("VAROVÁNÍ: mapování ukazuje na neexistující ikony:", sorted(missing))
    for theme, meta in VARIANTS.items():
        theme_dir = out_dir / theme
        if theme_dir.exists():
            shutil.rmtree(theme_dir)  # jinak zůstávají zastaralé soubory z předchozích buildů
        theme_dir.mkdir(parents=True)
        (theme_dir / "index.theme").write_text(index_theme(theme, meta), encoding="utf-8")
        count = 0
        for name, (attrs, inner) in icons.items():
            f = theme_dir / "scalable" / "apps" / f"{name}.svg"
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_text(render_icon(attrs, inner, theme), encoding="utf-8")
            count += 1
        # logo aplikace — branding zůstává barevný ve všech variantách
        for alias in ("cz.svec.Studio", "svec-studio"):
            (theme_dir / "scalable" / "apps" / f"{alias}.svg").write_text(logo, encoding="utf-8")
            count += 1
        # standardní freedesktop jména → přebírají systémové ikony
        for ctx, mapping in FDO_MAP.items():
            ctx_dir = theme_dir / "scalable" / ctx
            ctx_dir.mkdir(parents=True, exist_ok=True)
            for fdo_name, src in mapping.items():
                fname = fdo_name.replace("/", "-")  # x-scheme-handler/magnet → x-scheme-handler-magnet.svg
                if src == "cz.svec.Studio":
                    (ctx_dir / f"{fname}.svg").write_text(logo, encoding="utf-8")
                elif src in icons:
                    attrs, inner = icons[src]
                    (ctx_dir / f"{fname}.svg").write_text(render_icon(attrs, inner, theme), encoding="utf-8")
                count += 1
        # syntetizované ikony (baterie apod. — bez svec-* zdroje)
        for ctx, synth in SYNTH_ICONS.items():
            ctx_dir = theme_dir / "scalable" / ctx
            ctx_dir.mkdir(parents=True, exist_ok=True)
            for name, (attrs, inner) in synth.items():
                (ctx_dir / f"{name}.svg").write_text(render_icon(attrs, inner, theme), encoding="utf-8")
                count += 1
        print(f"{theme}: {count} ikon → {theme_dir}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT, help="výstupní adresář (výchozí packaging/iconpack)")
    ap.add_argument("--install", action="store_true", help="zkopírovat themy do ~/.local/share/icons/")
    args = ap.parse_args()

    build_themes(args.out)

    if args.install:
        for theme in VARIANTS:
            src = args.out / theme
            dst = INSTALL_DIR / theme
            if dst.exists():
                shutil.rmtree(dst)
            shutil.copytree(src, dst)
            print(f"installed: {dst}")
        print("\nVyber v System Settings → Icons (nebo Icons= v Plasma tématu).")


if __name__ == "__main__":
    main()
