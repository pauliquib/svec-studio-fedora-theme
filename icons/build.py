_ENTRY_RE = re.compile(r'(?:^|,)\s*(?:(\w+)|"([^"]+)")\s*:\s*\'((?:[^\'\\]|\\.)*)\'', re.S)
_SVG_RE = re.compile(r"<svg\b([^>]*)>([\s\S]*?)</svg>")
_STRIP_ATTRS_RE = re.compile(r'\s(?:aria-hidden|width|height|id|version|class)="[^"]*"')
_VIEWBOX_RE = re.compile(r'viewBox="([^"]*)"')
_NONPAINT_RE = re.compile(r'\s(?:xmlns(?::\w+)?|viewBox)="[^"]*"')


def _js_block(text: str, marker: str) -> str:
    """Vrátí tělo `{ ... }` za `marker` (např. 'export const ICONS =')."""
    start = text.index(marker)
    brace = text.index("{", start)
    depth = 0
    i = brace
    in_str = False
    while i < len(text):
        ch = text[i]
        if in_str:
            if ch == "\\":
                i += 2
                continue
            if ch == "'":
                in_str = False
        elif ch == "'":
            in_str = True
        elif ch == "{":
            depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                return text[brace + 1 : i]
        i += 1
    raise ValueError(f"neuzavřený blok za {marker!r}")


def js_svg_entries(path: Path, marker: str) -> dict[str, str]:
    """Klíč → inline SVG (nebo SVG inner) z JS objektu."""
    body = _js_block(path.read_text(encoding="utf-8"), marker)
    body = re.sub(r"/\*[\s\S]*?\*/", "", body)
    body = re.sub(r"//[^\n]*", "", body)
    out: dict[str, str] = {}
    for m in _ENTRY_RE.finditer(body):
        key = m.group(1) or m.group(2)
        val = m.group(3)
        if "<svg" in val or "<path" in val or "<circle" in val or "<rect" in val:
            out[key] = val
    return out


def split_svg(svg: str) -> tuple[str, str]:
    """(atributy <svg>, vnitřek) — normalizuje xmlns/viewBox, odstraní šum."""
    m = _SVG_RE.search(svg)
    if not m:
        raise ValueError("není SVG")
    attrs = _STRIP_ATTRS_RE.sub("", m.group(1))
    inner = m.group(2).strip()
    if "xmlns=" not in attrs:
        attrs = ' xmlns="http://www.w3.org/2000/svg"' + attrs
    if "viewBox=" not in attrs:
        attrs += ' viewBox="0 0 24 24"'
    return attrs, inner


def wrap_inner(inner: str) -> str:
    """Holý SVG inner → standardní Studio root (KIT_ICONS, syntetika)."""
    return (
        ' xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none"'
        ' stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"',
        inner,
    )


def _battery_inner(level: float | None, mark: str | None = None) -> str:
    """Outline baterie ve stylu Studia: tělo + hrot; level = výplň, mark = bolt/!/x."""
    parts = ['<rect x="2.5" y="8" width="17" height="9" rx="2"/>', '<path d="M22 11v3"/>']
    if level:
        w = round(13 * level, 2)
        parts.append(f'<rect x="4.5" y="10" width="{w}" height="5" rx="0.6" fill="currentColor" stroke="none"/>')
    if mark == "bolt":
        parts.append('<path d="M13 9.5l-2.7 3.6h2.1l-1.5 3.4 3.4-4.2h-2.3l1-3.4z" fill="currentColor" stroke="none"/>')
    elif mark == "exclaim":
        parts += ['<path d="M12 10v3"/>', '<path d="M12 15.2v.01"/>']
    elif mark == "cross":
        parts.append('<path d="M8 10l5 5M13 10l-5 5"/>')
    return "\n  ".join(parts)


def synth_status_icons() -> dict[str, tuple[str, str]]:
    """Tray/status ikony, které ve zdrojích chybí — baterie (Plasma naming)."""
    out: dict[str, tuple[str, str]] = {}
    for pct in range(0, 101, 10):
        name = f"battery-{pct:03d}"
        out[name] = wrap_inner(_battery_inner(pct / 100))
        out[f"{name}-charging"] = wrap_inner(_battery_inner(None, "bolt"))
    out["battery"] = wrap_inner(_battery_inner(0.7))
    out["battery-charging"] = wrap_inner(_battery_inner(None, "bolt"))
    out["battery-caution"] = wrap_inner(_battery_inner(None, "exclaim"))
    out["battery-caution-charging"] = wrap_inner(_battery_inner(None, "bolt"))
    out["battery-low"] = wrap_inner(_battery_inner(0.15))
    out["battery-low-charging"] = wrap_inner(_battery_inner(None, "bolt"))
    out["battery-full"] = wrap_inner(_battery_inner(1.0))
    out["battery-full-charged"] = wrap_inner(_battery_inner(1.0))
    out["battery-full-charging"] = wrap_inner(_battery_inner(None, "bolt"))
    out["battery-missing"] = wrap_inner(_battery_inner(None, "cross"))
    out["ups-battery"] = wrap_inner(_battery_inner(0.7))
    out["ups-charging"] = wrap_inner(_battery_inner(None, "bolt"))
    return out


